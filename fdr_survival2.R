a <- read.csv("results/survival/cox_arrays_robust.csv")
cat("Genes tested in all cohorts:", nrow(a), "\n")
fl <- function(p) pmin(pmax(p, 5e-5), 0.9999)
mk <- function(hr, p) { b <- log(hr); list(b=b, se=abs(b)/qnorm(1 - fl(p)/2)) }
A <- mk(a$HR_A, a$p_A); B <- mk(a$HR_B, a$p_B); T <- mk(a$HR_T, a$p_T)
w <- cbind(1/A$se^2, 1/B$se^2, 1/T$se^2)
b <- cbind(A$b, B$b, T$b)
bp <- rowSums(w*b)/rowSums(w); sep <- 1/sqrt(rowSums(w))
Q <- rowSums(w*(b - bp)^2)
a$HR_pooled <- round(exp(bp), 2)
a$p_pooled <- 2*pnorm(-abs(bp/sep))
a$fdr_pooled <- p.adjust(a$p_pooled, "BH")
a$I2 <- round(pmax(0, (Q - 2)/Q)*100)
a$same_dir <- (a$HR_A > 1) == (a$HR_B > 1) & (a$HR_B > 1) == (a$HR_T > 1)
o <- order(a$p_pooled)
cols <- c("gene","HR_A","HR_B","HR_T","HR_pooled","p_pooled","fdr_pooled","I2","same_dir","comp","new","p_pro")
a$p_pooled <- signif(a$p_pooled, 2); a$fdr_pooled <- signif(a$fdr_pooled, 2)
cat("Genes with pooled FDR<0.05:", sum(a$fdr_pooled < 0.05), "| and same direction in all 3:",
    sum(a$fdr_pooled < 0.05 & a$same_dir), "\n\n")
print(head(a[o, cols], 25), row.names=FALSE)
write.csv(a[o, ], "results/survival/survival_meta_fdr.csv", row.names=FALSE)
